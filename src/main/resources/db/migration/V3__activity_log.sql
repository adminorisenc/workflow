-- Local audit of authenticated API write attempts. Keep identity and route without request bodies.
create table if not exists activity_log (
  id bigint generated by default as identity primary key,
  actor_object_id varchar(200) not null,
  actor_name varchar(320),
  http_method varchar(10) not null,
  route varchar(500) not null,
  resource_ref varchar(200),
  status_code integer,
  occurred_at timestamp with time zone not null default current_timestamp
);
create index if not exists idx_activity_log_time on activity_log (occurred_at desc, id desc);
create index if not exists idx_activity_log_actor_time on activity_log (actor_object_id, occurred_at desc);
